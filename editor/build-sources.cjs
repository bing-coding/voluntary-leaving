// Regenerate after changing game source, before publishing an editorial baseline.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const cp = require('node:child_process');
const root = path.resolve(__dirname, '..');
const paths = ['index.html', 'game-data.js', 'app.js', 'style.css',
  'scripts/constants.js', 'scripts/rules.js', 'scripts/state.js', 'scripts/actions.js',
  'scripts/views/core.js', 'scripts/views/portal.js', 'scripts/views/systems.js',
  'scripts/views/review.js', 'scripts/modals/index.js'];
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
const files = paths.map(file => {
  const content = fs.readFileSync(path.join(root, file), 'utf8');
  return { path: file, sha256: sha(content), content };
});
const baseline = sha(files.map(file => `${file.path}:${file.sha256}`).join('\n'));
let sourceRevision = 'local';
try { sourceRevision = cp.execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim(); } catch (_) {}
const output = '// Generated by node editor/build-sources.cjs. Do not edit by hand.\nwindow.VoluntaryLeaveCopySources = ' + JSON.stringify({ baseline, sourceRevision, files }) + ';\n';
if (process.argv.includes('--check')) {
  const existing = fs.readFileSync(path.join(__dirname, 'sources.js'), 'utf8');
  const vm = require('node:vm');
  const context = { window: {} };
  vm.runInNewContext(existing, context);
  if (context.window.VoluntaryLeaveCopySources.baseline !== baseline) {
    console.error('Game source changed; regenerate editor/sources.js before reviewing or publishing.');
    process.exit(1);
  }
  console.log('ok - editorial baseline matches game source');
} else {
  fs.writeFileSync(path.join(__dirname, 'sources.js'), output);
  console.log(`Generated editorial baseline ${baseline.slice(0, 12)} (${files.length} files).`);
}
